// ============================================================================
// Отработка возражений (FR4, UC-05).
//
// По тексту возражения определяем его тип, готовим 2–3 варианта ответа клиенту
// (эмпатичных и конкретных) с пояснением «почему это работает» для менеджера,
// список «чего говорить НЕ стоит» (с учётом ограничений клиента) и, при
// чувствительном возражении, строку эскалации профильному специалисту.
//
// Чистые функции, без сайд-эффектов и без импорта модулей данных.
// ============================================================================

import type { ObjectionOption, ObjectionResult, Product } from "../domain/types";
import { type AIContext, firstName } from "./context";

type ObjectionType =
  | "риск"
  | "цена/комиссии"
  | "тайминг"
  | "сервис/доверие"
  | "сложность"
  | "конкурент"
  | "общее сомнение";

const PATTERNS: Array<{ type: ObjectionType; re: RegExp }> = [
  { type: "риск", re: /риск|нервно|пик|опаса|страшно|боюсь|просед|волатил/i },
  { type: "цена/комиссии", re: /дорого|комисс|ставк|переплач|цена|стоит дорого/i },
  { type: "тайминг", re: /позже|не сейчас|подожд|тайминг|время не|не время|потом/i },
  { type: "сервис/доверие", re: /сервис|задержк|недовол|раздража|подвел|ошибк|сбой|доверие|обман/i },
  { type: "сложность", re: /сложно|длинн|перегруж|запутан|непонятн|много букв|разобрат/i },
  { type: "конкурент", re: /другой банк|условия лучше|у них|в другом|конкурент|предлагают лучше/i },
];

function detectType(text: string): ObjectionType {
  for (const p of PATTERNS) {
    if (p.re.test(text)) return p.type;
  }
  return "общее сомнение";
}

function leadProduct(ctx: AIContext): Product | null {
  return ctx.relevantProducts.length > 0 ? ctx.relevantProducts[0] : null;
}

interface ConstraintFlags {
  noPressure: boolean;
  short: boolean;
  oneTopic: boolean;
  noCall: boolean;
  serviceFirst: boolean;
  ownership: boolean;
}

function readConstraints(constraints: string[]): ConstraintFlags {
  const has = (...keys: string[]) => keys.some((k) => constraints.includes(k));
  return {
    noPressure: has("avoid_pressure", "no_pressure", "timing_risk", "timing"),
    short: has("keep_message_short", "no_long_messages", "avoid_long_presentation", "avoid_long_terms", "mobile_format_only"),
    oneTopic: has("separate_topics", "avoid_topic_mixing"),
    noCall: has("no_call"),
    serviceFirst: has("no_sales_push", "negative_service"),
    ownership: has("show_ownership"),
  };
}

export function generateObjection(ctx: AIContext, objectionText: string): ObjectionResult {
  const name = firstName(ctx);
  const type = detectType(objectionText);
  const flags = readConstraints(ctx.insight?.constraints ?? []);
  const lead = leadProduct(ctx);
  const sentiment = ctx.insight?.sentiment ?? null;

  const options = buildOptions(name, type, lead, flags);
  const avoid = buildAvoid(type, flags);
  const escalate = buildEscalation(type, sentiment, objectionText);

  return {
    objectionText,
    objectionType: type,
    options,
    avoid,
    escalate,
  };
}

// ----------------------------------------------------------------------------
// Варианты ответов по типу возражения.
// ----------------------------------------------------------------------------

function buildOptions(
  name: string,
  type: ObjectionType,
  lead: Product | null,
  flags: ConstraintFlags,
): ObjectionOption[] {
  // При сервис-первом сценарии не называем продукт в ответе на цену/риск —
  // продажи в моменте недопустимы, говорим о решении задачи нейтрально.
  const prod = lead && !flags.serviceFirst ? `«${lead.name}»` : "подходящее решение";

  switch (type) {
    case "риск":
      return [
        {
          title: "Признать опасение и снизить шаг входа",
          response: `${name}, понимаю, что сейчас входить на всю сумму некомфортно. Можно начать с небольшой части и поэтапно — так вы контролируете риск и видите результат, прежде чем двигаться дальше.`,
          rationale: "Не спорим с эмоцией, а снижаем цену ошибки: поэтапный вход снимает страх необратимого решения.",
        },
        {
          title: "Сместить акцент на защиту капитала",
          response: `${name}, для вашей задачи важнее не максимальная доходность, а спокойствие. Давайте посмотрим консервативную часть, где капитал защищён, а доходность всё равно выше базовой.`,
          rationale: "Переводим разговор с «риска» на «контроль», что соответствует осторожному настрою клиента.",
        },
        {
          title: "Дать ориентир по сценариям",
          response: `${name}, чтобы решение было осознанным, покажу два-три сценария с разным уровнем риска — без давления, просто чтобы вы видели логику.`,
          rationale: "Прозрачность сценариев возвращает клиенту чувство контроля и снижает тревогу.",
        },
      ];

    case "цена/комиссии":
      return [
        {
          title: "Перевести на ценность, а не на цену",
          response: `${name}, давайте посмотрим не на комиссию отдельно, а на итог в ваших деньгах. По ${prod} чистый результат обычно перекрывает расходы — посчитаю на ваших цифрах.`,
          rationale: "Сравнение «нетто-результата» обезоруживает возражение о цене конкретикой, а не оправданиями.",
        },
        {
          title: "Показать прозрачность условий",
          response: `${name}, у нас нет скрытых платежей — разложу все условия по пунктам, чтобы вы видели, за что именно платите.`,
          rationale: "Прозрачность снимает подозрение о переплате и укрепляет доверие.",
        },
        {
          title: "Предложить подходящий по бюджету формат",
          response: `${name}, если хочется аккуратнее по затратам, подберу вариант с меньшим порогом входа — ценность сохраним, расходы уменьшим.`,
          rationale: "Даём выбор вместо торга: клиент сам выбирает комфортный уровень, не теряя ценности.",
        },
      ];

    case "тайминг":
      return [
        {
          title: "Согласиться и зафиксировать удобное окно",
          response: `${name}, абсолютно нормально не торопиться. Давайте я просто вернусь в удобное вам время — подскажите, когда комфортно, и до тех пор не беспокою.`,
          rationale: "Не давим на «сейчас»: уважение к таймингу клиента сохраняет отношения и право на следующий контакт.",
        },
        {
          title: "Оставить короткий ориентир на будущее",
          response: `${name}, чтобы не терять время, когда тема станет актуальной, пришлю одно короткое резюме — вернётесь к нему, когда будете готовы.`,
          rationale: "Лёгкий «якорь» без обязательств держит тему живой и не выглядит навязчивым.",
        },
      ];

    case "сервис/доверие":
      return [
        {
          title: "Взять ответственность и извиниться",
          response: `${name}, мне жаль, что так вышло — это моя зона ответственности. Разберусь лично и вернусь к вам с решением, а не с отписками.`,
          rationale: "Признание ответственности — единственный способ восстановить доверие; оправдания его разрушают.",
        },
        {
          title: "Сначала решить, потом всё остальное",
          response: `${name}, сейчас для меня в приоритете закрыть именно этот вопрос. Никаких продуктов и предложений — давайте сначала уберём проблему.`,
          rationale: "Сервис вперёд продаж: смешивать тему с продажей в момент негатива недопустимо.",
        },
        {
          title: "Дать конкретику по срокам",
          response: `${name}, чтобы это не повисло: назову конкретный срок, к которому вернусь с результатом, и проконтролирую сам.`,
          rationale: "Конкретный срок и личный контроль возвращают клиенту ощущение, что его слышат.",
        },
      ];

    case "сложность":
      return [
        {
          title: "Свернуть до сути в одном сообщении",
          response: `${name}, упрощаю: суть в одном предложении и один следующий шаг. Если зайдёт — раскрою детали, если нет — на этом остановимся.`,
          rationale: "Сокращение когнитивной нагрузки снимает возражение «слишком сложно» лучше любых пояснений.",
        },
        {
          title: "Предложить формат «по шагам»",
          response: `${name}, давайте не всё сразу. Разберём по одному шагу за раз, в удобном вам темпе — без перегруза.`,
          rationale: "Дробление на шаги делает решение посильным и снимает ощущение «много всего».",
        },
      ];

    case "конкурент":
      return [
        {
          title: "Сравнить честно, по фактам",
          response: `${name}, давайте сравним по пунктам — без маркетинга. Если у коллег где-то лучше, прямо скажу; зато покажу, где вы выигрываете у нас.`,
          rationale: "Честное сравнение вызывает доверие сильнее, чем огульная критика конкурента.",
        },
        {
          title: "Подсветить персональный сервис",
          response: `${name}, ставка — это половина истории. Вторая половина — что у вас есть персональный менеджер, который ведёт вопрос лично; это и есть разница.`,
          rationale: "Переводим разговор со «ставки» на сервис и отношения — то, что конкурент не скопирует.",
        },
      ];

    default:
      return [
        {
          title: "Уточнить настоящую причину сомнения",
          response: `${name}, чтобы быть полезным, а не просто настойчивым: подскажите, что именно вызывает сомнение? Так подберу вариант точно под вашу ситуацию.`,
          rationale: "За общим сомнением обычно стоит конкретная причина — вопрос вскрывает её без давления.",
        },
        {
          title: "Снять давление и оставить выбор",
          response: `${name}, никакой спешки. Я просто оставлю короткое резюме, а решение полностью за вами — вернёмся к нему, когда будет удобно.`,
          rationale: "Снятие давления сохраняет отношения и оставляет дверь открытой для следующего шага.",
        },
      ];
  }
}

// ----------------------------------------------------------------------------
// «Чего говорить НЕ стоит» — с учётом ограничений клиента.
// ----------------------------------------------------------------------------

function buildAvoid(type: ObjectionType, flags: ConstraintFlags): string[] {
  const avoid: string[] = [];

  // Базовое — по типу возражения.
  switch (type) {
    case "риск":
      avoid.push("Не обесценивайте опасение («да тут вообще нет риска»).");
      avoid.push("Не давите на упущенную выгоду и не торопите с решением.");
      break;
    case "цена/комиссии":
      avoid.push("Не спорьте о цене в лоб и не оправдывайтесь за комиссию.");
      avoid.push("Не обещайте «эксклюзивных скидок», которых нет.");
      break;
    case "тайминг":
      avoid.push("Не создавайте искусственную срочность («предложение только сегодня»).");
      avoid.push("Не напоминайте о себе слишком часто.");
      break;
    case "сервис/доверие":
      avoid.push("Не перекладывайте вину на клиента, систему или коллег.");
      avoid.push("Не переходите к продаже, пока проблема не решена.");
      break;
    case "сложность":
      avoid.push("Не заваливайте деталями и терминами.");
      avoid.push("Не отправляйте длинные сообщения и таблицы.");
      break;
    case "конкурент":
      avoid.push("Не критикуйте другой банк эмоционально и голословно.");
      avoid.push("Не обещайте «перебить любые условия» без расчёта.");
      break;
    default:
      avoid.push("Не настаивайте, не выяснив реальную причину сомнения.");
      avoid.push("Не предлагайте всё подряд в надежде угадать.");
  }

  // Поверх — ограничения клиента из инсайта.
  if (flags.noPressure) avoid.push("Никакого давления и срочности — клиент это плохо переносит.");
  if (flags.short) avoid.push("Без длинных сообщений — держите ответ коротким.");
  if (flags.oneTopic) avoid.push("Не смешивайте темы — обсуждаем строго один вопрос.");
  if (flags.noCall) avoid.push("Не предлагайте звонок — клиент предпочитает переписку.");
  if (flags.serviceFirst) avoid.push("Никаких продуктовых предложений сейчас — только сервис.");

  // Убираем дубли и ограничиваем 4 пунктами.
  return Array.from(new Set(avoid)).slice(0, 4);
}

// ----------------------------------------------------------------------------
// Эскалация — только для чувствительных возражений.
// ----------------------------------------------------------------------------

const FORCE_MAJEURE = /блокиров|мошенн|форс-?мажор|украл|взлом|списа.*без|двойн.*списа/i;

function buildEscalation(
  type: ObjectionType,
  sentiment: string | null,
  objectionText: string,
): string | null {
  if (FORCE_MAJEURE.test(objectionText)) {
    return "Передать профильному специалисту: возможный инцидент безопасности или форс-мажор — требует немедленной проверки и не решается в рамках обычного диалога.";
  }
  if (type === "сервис/доверие" && (sentiment === "negative" || sentiment === "tense")) {
    return "Передать профильному специалисту: жалоба на сервис с негативным настроем — подключить сервис-команду и держать вопрос на личном контроле до решения.";
  }
  return null;
}
